#!/usr/bin/env bash
# Apply the Feishu tool-summary aggregation fix (wayE) to an installed
# @openclaw/feishu monitor bundle.
#
# Usage:
#   ./install.sh [--check|--dry-run] <path-to-installed-monitor.account-*.mjs>
#
#   --check    Report pristine/patched/unknown and exit (no changes).
#   --dry-run  Validate the exact build and print what would happen.
#
# The target is the plugin's compiled bundle, typically found under:
#   <openclaw-home>/npm/projects/*/node_modules/@openclaw/feishu/dist/.setup/monitor.account-*.mjs
#
# The installer detects the target's build by SHA-256, selects the matching
# per-version patch, and applies it. It is idempotent: re-running on an
# already-patched file reports "already patched".
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

# BEGIN GENERATED VERSIONS
# version -> "pristine_sha patched_sha patch_path"; regenerated by tools/finalize.py
VERSIONS=(
  "2026.11.1 6dbfa74bcad154b68d206f7d54883b8679a3b308332954a29f2d0f91af7bddb7 b7ae62a883a10d15ce5e67fdf10ec30bcee277ad6e7b38a97ca7292112bb03be 1f67ad1ed00bd7d8a004cf8186928881035886d608f9dc0c3d86eaa3fef4ef49 $HERE/patches/2026.11.1/feishu-tool-aggregation.patch"
  "2026.11.2 44f6d50f1fe6dbfa9cfb12aef47e954589391929721d985deb2ecf976de4aab6 9ea34a8dbb30de75a3b3c1a39d12785c583be68010d56edba27dbf258952a63d 530ccc57517e1b6902ecaa0ddd4b6b66fff8fe9677cbd12af975176f7012b750 $HERE/patches/2026.11.2/feishu-tool-aggregation.patch"
)
# END GENERATED VERSIONS
# BEGIN GENERATED UPGRADES
# from_sha -> "to_sha patch_sha patch_path"; regenerated by tools/finalize.py
UPGRADES=(
)
# END GENERATED UPGRADES

usage() {
  echo "usage: $0 [--check|--dry-run] <path-to-monitor.account-*.mjs>" >&2
}

die() {
  echo "error: $*" >&2
  exit 1
}

sum() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    die "neither sha256sum nor shasum is available"
  fi
}

MODE="apply"
TARGET=""
while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE="check"; shift ;;
    --dry-run) MODE="dryrun"; shift ;;
    -h|--help) usage; exit 0 ;;
    --) shift; break ;;
    -*) die "unknown option: $1" ;;
    *) TARGET="$1"; shift ;;
  esac
done
if [ -z "$TARGET" ]; then usage; exit 2; fi
if [ ! -f "$TARGET" ]; then die "not a file: $TARGET"; fi

CUR="$(sum "$TARGET")"
PATCHED_VERSION=""
PRISTINE_MATCH=""
UPGRADE_MATCH=""
for v in "${VERSIONS[@]}"; do
  read -r ver pristine patched patch_sha patch <<<"$v"
  if [ "$CUR" = "$patched" ]; then PATCHED_VERSION="$ver"; fi
  if [ "$CUR" = "$pristine" ]; then PRISTINE_MATCH="$ver $patched $patch_sha $patch"; fi
done
# bash 3.2 (macOS) treats an empty array expansion as unbound under `set -u`;
# the `-` fallback keeps the no-upgrade case compatible.
for u in ${UPGRADES[@]-}; do
  read -r from_sha to_sha patch_sha patch <<<"$u"
  if [ "$CUR" = "$from_sha" ]; then UPGRADE_MATCH="$from_sha $to_sha $patch_sha $patch"; fi
done

if [ -n "$PATCHED_VERSION" ]; then
  if [ "$MODE" = "check" ]; then echo "status=patched version=$PATCHED_VERSION target=$TARGET"; fi
  echo "already patched (plugin build $PATCHED_VERSION; $TARGET)"
  exit 0
fi

ACTION=""
VER=""
FROM_SHA=""
EXPECTED_PATCHED=""
EXPECTED_PATCH_SHA=""
PATCH=""
if [ -n "$PRISTINE_MATCH" ]; then
  read -r VER EXPECTED_PATCHED EXPECTED_PATCH_SHA PATCH <<<"$PRISTINE_MATCH"
  ACTION="pristine"
elif [ -n "$UPGRADE_MATCH" ]; then
  read -r FROM_SHA EXPECTED_PATCHED EXPECTED_PATCH_SHA PATCH <<<"$UPGRADE_MATCH"
  ACTION="upgrade"
  VER="$(basename "$(dirname "$PATCH")")"
else
  if [ "$MODE" = "check" ]; then echo "status=unknown sha256=$CUR target=$TARGET"; fi
  echo "error: $TARGET does not match any known pristine or upgradable plugin build." >&2
  echo "  actual sha256: $CUR" >&2
  echo "Known pristine builds:" >&2
  for v in "${VERSIONS[@]}"; do read -r ver pristine patched patch_sha patch <<<"$v"; echo "  $ver  $pristine" >&2; done
  if [ ${#UPGRADES[@]} -gt 0 ]; then
    echo "Known upgradable builds:" >&2
    for u in "${UPGRADES[@]}"; do read -r from_sha to_sha patch_sha patch <<<"$u"; echo "  $from_sha -> $(basename "$(dirname "$patch")")" >&2; done
  fi
  echo "This patch targets specific builds; re-derive it for a new release." >&2
  exit 1
fi

if [ ! -f "$PATCH" ]; then die "patch file missing: $PATCH"; fi
ACTUAL_PATCH_SHA="$(sum "$PATCH")"
if [ "$ACTUAL_PATCH_SHA" != "$EXPECTED_PATCH_SHA" ]; then
  die "patch file hash mismatch (expected $EXPECTED_PATCH_SHA, got $ACTUAL_PATCH_SHA)"
fi
if [ "$MODE" = "check" ]; then
  if [ "$ACTION" = "upgrade" ]; then
    echo "status=upgradable from=$FROM_SHA to_version=$VER target=$TARGET"
  else
    echo "status=pristine version=$VER target=$TARGET"
  fi
  exit 0
fi
if [ "$MODE" = "dryrun" ]; then
  if [ "$ACTION" = "upgrade" ]; then
    echo "would upgrade version=$VER target=$TARGET patch=$PATCH"
  else
    echo "would patch (pristine) version=$VER target=$TARGET patch=$PATCH"
  fi
  exit 0
fi

DIR="$(dirname "$TARGET")"
LOCK="$DIR/.monitor-install.lock"
if ! mkdir "$LOCK" 2>/dev/null; then
  die "another install is in progress (lock: $LOCK)"
fi
TMP=""
cleanup() {
  if [ -n "$TMP" ] && [ -f "$TMP" ]; then rm -f "$TMP"; fi
  rmdir "$LOCK" 2>/dev/null || true
}
trap cleanup EXIT

BAK="$DIR/.monitor.backup-$(date -u +%Y%m%dT%H%M%SZ).mjs"
cp -p "$TARGET" "$BAK"
echo "backup: $BAK"
echo "applying $ACTION for plugin build $VER"

TMP="$(mktemp "$DIR/.monitor.patch.XXXXXX")"
cp -p "$TARGET" "$TMP"
if ! patch -p0 "$TMP" < "$PATCH"; then
  rm -f "$TMP"
  TMP=""
  echo "error: patch failed; target unchanged (backup: $BAK)." >&2
  exit 1
fi
NEW="$(sum "$TMP")"
if [ "$NEW" != "$EXPECTED_PATCHED" ]; then
  rm -f "$TMP"
  TMP=""
  echo "error: post-patch hash mismatch; target unchanged (backup: $BAK)." >&2
  exit 1
fi
if ! mv -f "$TMP" "$TARGET"; then
  die "could not replace target: $TARGET (backup: $BAK)"
fi
TMP=""
echo "patched OK: $TARGET"
echo "sha256: $NEW"
echo "Restart the gateway for the change to take effect."
