#!/usr/bin/env bash
# Apply the Feishu tool-summary aggregation fix (wayE) to an installed
# @openclaw/feishu monitor bundle.
#
# Usage:
#   ./install.sh [--check|--dry-run] <path-to-installed-monitor.account-*.mjs>
#
#   --check    Report pristine/patched/unknown and exit (no changes).
#   --dry-run  Validate the exact build and print what would happen.
#
# The target is the plugin's compiled bundle, typically found under:
#   <openclaw-home>/npm/projects/*/node_modules/@openclaw/feishu/dist/.setup/monitor.account-*.mjs
#
# The installer detects the target's build by SHA-256, selects the matching
# per-version patch, and applies it. It is idempotent: re-running on an
# already-patched file reports "already patched".
#
# In-place upgrade: a bundle patched by an *older* release is recognised through
# the generated KNOWN_PATCHED list. Because the patch is generated against the
# pristine bytes, the installer restores a pristine copy from a sibling
# `.monitor.backup-*.mjs` whose hash matches, then patches forward. If no
# pristine backup is left, the plugin has to be reinstalled first.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
KEEP_BACKUPS=3
LOCK_STALE_SECONDS=900

# BEGIN GENERATED VERSIONS
# version -> "pristine_sha patched_sha patch_sha patch_path"; regenerated by tools/finalize.py
VERSIONS=(
  "2026.11.1 6dbfa74bcad154b68d206f7d54883b8679a3b308332954a29f2d0f91af7bddb7 a5664b511b5004199dba5cbe777c12d7c39fc4c7a70e585fd81236646ecf7a84 485950c853b37ede8fa02da5a53a8be064f119a212ff4e6294a11b9d1006c1dd $HERE/patches/2026.11.1/feishu-tool-aggregation.patch"
  "2026.11.2 44f6d50f1fe6dbfa9cfb12aef47e954589391929721d985deb2ecf976de4aab6 2472f7a1637391eeb07ba133c61d4acd190031ccf4c82a42551534216ded2864 de564abef3ba8d746f33b39db41b6b22e1b38931f02a0dc6ca9445395a6a9348 $HERE/patches/2026.11.2/feishu-tool-aggregation.patch"
)
# END GENERATED VERSIONS
# BEGIN GENERATED UPGRADES
# from_sha -> "to_sha patch_sha patch_path"; regenerated by tools/finalize.py
UPGRADES=(
)
# END GENERATED UPGRADES
# BEGIN GENERATED KNOWN_PATCHED
# previous patched_sha -> "version"; lets the installer restore pristine from .monitor.backup-*.mjs
KNOWN_PATCHED=(
  "2796212ba2507d4d81a6c4b95e645d10e8f3706beb25b91540662bc369a34ce2 2026.11.2"
  "ee93e269edf1717c2ae541bf1d343813c69055f5cd31f0c0d370e849f9e2194d 2026.11.2"
  "53f7c53f95ff2da90a91e9fcc98ae10bf474c94ae55ad4d748e510cac6cc2725 2026.11.1"
  "dea21efcc5f405f94265ed369a620a9006ec1b503cc2e00d6dc6f70aced32576 2026.11.1"
  "2a1fcb97ae5a62daa401ff4a5c0992edece3eda585eef16399b0879ab84b8eb6 2026.11.2"
  "10572e74a295c682e1cd678f0e17d1e2632e4707dadbf930faed85e904e99da1 2026.11.1"
  "a63953bb1f886b31358ddbd8b84b9f6dd9a3c3fac2f16fddac521899e45dad62 2026.11.2"
)
# END GENERATED KNOWN_PATCHED

usage() {
  echo "usage: $0 [--check|--dry-run] <path-to-monitor.account-*.mjs>" >&2
}

die() {
  echo "error: $*" >&2
  exit 1
}

sum() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    die "neither sha256sum nor shasum is available"
  fi
}

# is_pristine_sha <sha> -> 0 when the hash is one of the supported pristine builds
is_pristine_sha() {
  local want="$1" ver pristine patched patch_sha patch
  for v in "${VERSIONS[@]}"; do
    read -r ver pristine patched patch_sha patch <<<"$v"
    if [ "$want" = "$pristine" ]; then return 0; fi
  done
  return 1
}

# find_pristine_backup <pristine_sha> -> echo the newest matching .monitor.backup-*.mjs
find_pristine_backup() {
  local want="$1" dir="$2" b
  for b in $(ls -1 "$dir"/.monitor.backup-*.mjs 2>/dev/null | sort -r || true); do
    if [ "$(sum "$b")" = "$want" ]; then echo "$b"; return 0; fi
  done
  return 1
}

# prune_backups <dir>: keep the newest $KEEP_BACKUPS copies, but never delete the
# last pristine copy (it is the rollback/upgrade source for this target).
prune_backups() {
  local dir="$1" count=0 kept_pristine=0 b sha
  local all
  all="$(ls -1 "$dir"/.monitor.backup-*.mjs 2>/dev/null | sort -r || true)"
  [ -n "$all" ] || return 0
  for b in $all; do
    count=$((count + 1))
    if [ "$count" -le "$KEEP_BACKUPS" ]; then
      if is_pristine_sha "$(sum "$b")"; then kept_pristine=1; fi
      continue
    fi
    sha="$(sum "$b")"
    if [ "$kept_pristine" -eq 0 ] && is_pristine_sha "$sha"; then
      kept_pristine=1
      continue
    fi
    rm -f "$b" && echo "pruned backup: $b"
  done
}

MODE="apply"
TARGET=""
while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE="check"; shift ;;
    --dry-run) MODE="dryrun"; shift ;;
    -h|--help) usage; exit 0 ;;
    --) shift; break ;;
    -*) die "unknown option: $1" ;;
    *) TARGET="$1"; shift ;;
  esac
done
if [ -z "$TARGET" ]; then usage; exit 2; fi
if [ ! -f "$TARGET" ]; then die "not a file: $TARGET"; fi

CUR="$(sum "$TARGET")"
PATCHED_VERSION=""
PRISTINE_MATCH=""
UPGRADE_MATCH=""
KNOWN_MATCH=""
for v in "${VERSIONS[@]}"; do
  read -r ver pristine patched patch_sha patch <<<"$v"
  if [ "$CUR" = "$patched" ]; then PATCHED_VERSION="$ver"; fi
  if [ "$CUR" = "$pristine" ]; then PRISTINE_MATCH="$ver $patched $patch_sha $patch"; fi
done
# bash 3.2 (macOS) treats an empty array expansion as unbound under `set -u`;
# the `-` fallback keeps the no-upgrade / no-history case compatible.
if [ ${#UPGRADES[@]} -gt 0 ]; then
  for u in "${UPGRADES[@]}"; do
    read -r from_sha to_sha patch_sha patch <<<"$u"
    if [ "$CUR" = "$from_sha" ]; then UPGRADE_MATCH="$from_sha $to_sha $patch_sha $patch"; fi
  done
fi
if [ ${#KNOWN_PATCHED[@]} -gt 0 ]; then
  for k in "${KNOWN_PATCHED[@]}"; do
    read -r known_sha known_ver <<<"$k"
    if [ "$CUR" = "$known_sha" ]; then KNOWN_MATCH="$known_sha $known_ver"; fi
  done
fi

if [ -n "$PATCHED_VERSION" ]; then
  if [ "$MODE" = "check" ]; then echo "status=patched version=$PATCHED_VERSION target=$TARGET"; fi
  echo "already patched (plugin build $PATCHED_VERSION; $TARGET)"
  exit 0
fi

ACTION=""
VER=""
FROM_SHA=""
EXPECTED_PATCHED=""
EXPECTED_PATCH_SHA=""
PATCH=""
PRISTINE_BACKUP=""
if [ -n "$PRISTINE_MATCH" ]; then
  read -r VER EXPECTED_PATCHED EXPECTED_PATCH_SHA PATCH <<<"$PRISTINE_MATCH"
  ACTION="pristine"
elif [ -n "$UPGRADE_MATCH" ]; then
  read -r FROM_SHA EXPECTED_PATCHED EXPECTED_PATCH_SHA PATCH <<<"$UPGRADE_MATCH"
  ACTION="upgrade"
  VER="$(basename "$(dirname "$PATCH")")"
elif [ -n "$KNOWN_MATCH" ]; then
  read -r FROM_SHA VER <<<"$KNOWN_MATCH"
  for v in "${VERSIONS[@]}"; do
    read -r cv pristine patched patch_sha patch <<<"$v"
    if [ "$cv" = "$VER" ]; then
      EXPECTED_PATCHED="$patched"
      EXPECTED_PATCH_SHA="$patch_sha"
      PATCH="$patch"
      PRISTINE_BACKUP="$(find_pristine_backup "$pristine" "$(dirname "$TARGET")" || true)"
      break
    fi
  done
  if [ -z "$PATCH" ]; then die "known patched build $FROM_SHA maps to unsupported version $VER"; fi
  ACTION="rebase"
else
  if [ "$MODE" = "check" ]; then echo "status=unknown sha256=$CUR target=$TARGET"; fi
  echo "error: $TARGET does not match any known pristine, upgradable or previously patched plugin build." >&2
  echo "  actual sha256: $CUR" >&2
  echo "Known pristine builds:" >&2
  for v in "${VERSIONS[@]}"; do read -r ver pristine patched patch_sha patch <<<"$v"; echo "  $ver  $pristine" >&2; done
  if [ ${#UPGRADES[@]} -gt 0 ]; then
    echo "Known upgradable builds:" >&2
    for u in "${UPGRADES[@]}"; do read -r from_sha to_sha patch_sha patch <<<"$u"; echo "  $from_sha -> $(basename "$(dirname "$patch")")" >&2; done
  fi
  if [ ${#KNOWN_PATCHED[@]} -gt 0 ]; then
    echo "Known previously patched builds (rebase from .monitor.backup-*.mjs):" >&2
    for k in "${KNOWN_PATCHED[@]}"; do read -r known_sha known_ver <<<"$k"; echo "  $known_sha -> $known_ver" >&2; done
  fi
  echo "This patch targets specific builds; re-derive it for a new release." >&2
  exit 1
fi

if [ ! -f "$PATCH" ]; then die "patch file missing: $PATCH"; fi
ACTUAL_PATCH_SHA="$(sum "$PATCH")"
if [ "$ACTUAL_PATCH_SHA" != "$EXPECTED_PATCH_SHA" ]; then
  die "patch file hash mismatch (expected $EXPECTED_PATCH_SHA, got $ACTUAL_PATCH_SHA)"
fi
if [ "$MODE" = "check" ]; then
  case "$ACTION" in
    pristine) echo "status=pristine version=$VER target=$TARGET" ;;
    upgrade) echo "status=upgradable from=$FROM_SHA to_version=$VER target=$TARGET" ;;
    rebase)
      if [ -n "$PRISTINE_BACKUP" ]; then
        echo "status=patched version=$VER outdated=true upgradable=true pristine_backup=$PRISTINE_BACKUP target=$TARGET"
      else
        echo "status=patched version=$VER outdated=true upgradable=false pristine_backup=missing target=$TARGET"
      fi
      ;;
  esac
  exit 0
fi
if [ "$MODE" = "dryrun" ]; then
  case "$ACTION" in
    pristine) echo "would patch (pristine) version=$VER target=$TARGET patch=$PATCH" ;;
    upgrade) echo "would upgrade version=$VER target=$TARGET patch=$PATCH" ;;
    rebase)
      if [ -n "$PRISTINE_BACKUP" ]; then
        echo "would upgrade (rebase) version=$VER target=$TARGET pristine_backup=$PRISTINE_BACKUP patch=$PATCH"
      else
        echo "would fail: version=$VER target=$TARGET reason=no pristine backup (reinstall the plugin, then re-run)"
      fi
      ;;
  esac
  exit 0
fi
if [ "$ACTION" = "rebase" ] && [ -z "$PRISTINE_BACKUP" ]; then
  echo "error: $TARGET carries an older patch and no pristine $VER copy is left in $(dirname "$TARGET")." >&2
  echo "  reinstall @openclaw/feishu $VER (it restores dist/ as pristine), then re-run this installer." >&2
  exit 3
fi

DIR="$(dirname "$TARGET")"
LOCK="$DIR/.monitor-install.lock"
acquire_lock() {
  if mkdir "$LOCK" 2>/dev/null; then
    echo "$$" > "$LOCK/pid" 2>/dev/null || true
    date +%s > "$LOCK/at" 2>/dev/null || true
    return 0
  fi
  local owner age now
  owner="$(cat "$LOCK/pid" 2>/dev/null || true)"
  age="$(cat "$LOCK/at" 2>/dev/null || true)"
  now="$(date +%s)"
  if [ -n "$owner" ] && kill -0 "$owner" 2>/dev/null; then
    die "another install is in progress (pid $owner, lock: $LOCK)"
  fi
  if [ -n "$age" ] && [ $((now - age)) -lt "$LOCK_STALE_SECONDS" ]; then
    die "another install is in progress (lock: $LOCK); remove it if no install is running"
  fi
  if [ -n "$age" ]; then
    echo "removing stale install lock (pid ${owner:-unknown}, age $((now - age))s)" >&2
  else
    echo "removing stale install lock (pid ${owner:-unknown})" >&2
  fi
  rm -rf "$LOCK"
  mkdir "$LOCK" 2>/dev/null || die "could not acquire install lock: $LOCK"
  echo "$$" > "$LOCK/pid" 2>/dev/null || true
  date +%s > "$LOCK/at" 2>/dev/null || true
}
acquire_lock

TMP=""
cleanup() {
  if [ -n "$TMP" ]; then
    rm -f "$TMP" "$TMP.rej" "$TMP.orig"
  fi
  rm -rf "$LOCK" 2>/dev/null || true
}
trap cleanup EXIT

BAK="$DIR/.monitor.backup-$(date -u +%Y%m%dT%H%M%SZ).mjs"
cp -p "$TARGET" "$BAK"
echo "backup: $BAK"
SOURCE="$TARGET"
if [ "$ACTION" = "rebase" ]; then
  SOURCE="$PRISTINE_BACKUP"
  echo "restoring pristine $VER from $(basename "$PRISTINE_BACKUP")"
fi
echo "applying $ACTION for plugin build $VER"

TMP="$(mktemp "$DIR/.monitor.patch.XXXXXX")"
cp -p "$SOURCE" "$TMP"
if ! patch -p0 "$TMP" < "$PATCH"; then
  rm -f "$TMP" "$TMP.rej" "$TMP.orig"
  TMP=""
  echo "error: patch failed; target unchanged (backup: $BAK)." >&2
  exit 1
fi
NEW="$(sum "$TMP")"
if [ "$NEW" != "$EXPECTED_PATCHED" ]; then
  rm -f "$TMP" "$TMP.rej" "$TMP.orig"
  TMP=""
  echo "error: post-patch hash mismatch; target unchanged (backup: $BAK)." >&2
  exit 1
fi
if ! mv -f "$TMP" "$TARGET"; then
  die "could not replace target: $TARGET (backup: $BAK)"
fi
TMP=""
prune_backups "$DIR"
echo "patched OK: $TARGET"
echo "sha256: $NEW"
echo "Restart the gateway for the change to take effect."
